/** Byte strings with valid magic numbers for the sniffer. Not decodable images —
 *  cage never decodes them either, it serves bytes under the sniffed MIME. */
function pad(head: number[], seed: number, size = 64): Uint8Array {
  const out = new Uint8Array(Math.max(size, head.length))
  out.set(head, 0)
  for (let i = head.length; i < out.length; i++) out[i] = (i * 31 + seed) & 0xff
  return out
}
export const jpeg = (seed = 1): Uint8Array => pad([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01], seed)
export const png = (seed = 1): Uint8Array => pad([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d], seed)
export const gif = (seed = 1): Uint8Array => pad([0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00], seed)
export const webp = (seed = 1): Uint8Array => pad([0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x20], seed)
export const avif = (seed = 1): Uint8Array => pad([0x00, 0x00, 0x00, 0x1c, 0x66, 0x74, 0x79, 0x70, 0x61, 0x76, 0x69, 0x66], seed)
export const mp4 = (seed = 1): Uint8Array => pad([0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70, 0x69, 0x73, 0x6f, 0x6d], seed)
export const webm = (seed = 1): Uint8Array => pad([0x1a, 0x45, 0xdf, 0xa3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1f], seed)
export const notImage = (): Uint8Array => new TextEncoder().encode('<html><body>not an image at all, sorry</body></html>')
